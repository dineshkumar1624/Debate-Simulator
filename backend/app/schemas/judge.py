from typing import List, Optional, Literal, Dict, Any, Union
from pydantic import BaseModel, Field, model_validator

class CriterionScore(BaseModel):
    score: float = Field(ge=0.0, description="Score awarded for this criterion")
    max_score: float = Field(default=25.0, description="Maximum possible points for this criterion")
    reason: str = Field(default="", description="Detailed qualitative justification for the awarded score")
    supporting_message_refs: List[str] = Field(default_factory=list, description="References to supporting turns (e.g. ['Round 1 PRO'])")
    supporting_evidence_refs: List[str] = Field(default_factory=list, description="References to supporting citations (e.g. ['Evidence [1]'])")
    deductions_explanation: Optional[str] = Field(default=None, description="Explanation of why points were deducted")

class CitationAssessment(BaseModel):
    citation_id: Optional[str] = None
    source_reference: str
    speaker: Optional[str] = None
    verification_status: Literal["verified", "unverified", "fabricated", "contradicted"] = "unverified"
    claim_supported: bool = False
    details: str = ""

class JudgeRoundPoint(BaseModel):
    round_number: int
    pro_summary: str
    con_summary: str
    key_takeaway: str

class JudgeReportSchema(BaseModel):
    debate_id: Optional[str] = Field(default=None, description="Unique debate identifier")
    judge_provider: Optional[str] = Field(default="gemini", description="Judge service provider (gemini or nvidia)")
    judge_model: Optional[str] = Field(default=None, description="Model identifier used for adjudication")
    
    # 100-Point Scoring totals
    pro_total_score: float = Field(default=0.0, ge=0.0, le=100.0, description="Authoritative calculated total score for PRO (0-100)")
    con_total_score: float = Field(default=0.0, ge=0.0, le=100.0, description="Authoritative calculated total score for CON (0-100)")
    pro_score: float = Field(default=0.0, ge=0.0, le=100.0, description="Overall score for PRO (backward compatibility)")
    con_score: float = Field(default=0.0, ge=0.0, le=100.0, description="Overall score for CON (backward compatibility)")

    # 6 Standardized Criteria breakdowns
    pro_criteria_scores: Dict[str, CriterionScore] = Field(
        default_factory=dict,
        description="Detailed criterion scores for PRO across the 6-criterion rubric"
    )
    con_criteria_scores: Dict[str, CriterionScore] = Field(
        default_factory=dict,
        description="Detailed criterion scores for CON across the 6-criterion rubric"
    )

    winner: Literal["PRO", "CON", "INCONCLUSIVE", "FAILED"] = Field(description="Adjudicated winner, INCONCLUSIVE, or FAILED")
    verdict_type: Literal["DECISIVE_PRO", "DECISIVE_CON", "DRAW", "INCONCLUSIVE", "FAILED"] = Field(
        default="INCONCLUSIVE",
        description="Verdict classification based on margin of victory and evidence quality"
    )
    status: Literal["completed", "failed"] = Field(default="completed", description="Evaluation execution status")
    error_message: Optional[str] = Field(default=None, description="Error details if evaluation failed")

    # Qualitative analysis
    pro_strengths: List[str] = Field(default_factory=list)
    pro_weaknesses: List[str] = Field(default_factory=list)
    con_strengths: List[str] = Field(default_factory=list)
    con_weaknesses: List[str] = Field(default_factory=list)
    decisive_arguments: List[str] = Field(default_factory=list, description="Key turning points and decisive clashes")
    unsupported_claims: List[str] = Field(default_factory=list, description="Empirical assertions lacking documentary verification")
    citation_assessments: List[CitationAssessment] = Field(default_factory=list, description="Verification assessments for all citations")
    
    round_points: List[JudgeRoundPoint] = Field(default_factory=list)
    main_arguments: List[str] = Field(default_factory=list)
    main_counterarguments: List[str] = Field(default_factory=list)
    supported_claims: List[str] = Field(default_factory=list)
    judge_reasoning: str = Field(description="Detailed comparative evaluation of arguments and rebuttals")
    reasoning: Optional[str] = Field(default=None, description="Substantive comparative evaluation (alias)")
    balanced_verdict: str = Field(description="Balanced final synthesis and policy/epistemic conclusion")
    
    # Decoupled evidence reliability
    evidence_reliability_score: float = Field(ge=0.0, le=100.0, default=85.0)
    evidence_reliability: Optional[float] = Field(default=None, ge=0.0, le=100.0)
    
    source_references: List[str] = Field(default_factory=list)
    judge_model_used: Optional[str] = Field(default=None, description="Identifier of the model that performed adjudication")
    is_fallback: bool = Field(default=False, description="Whether this evaluation was generated by an offline fallback adjudicator")
    execution_status: Optional[Literal["REAL_REMOTE_API", "SIMULATED"]] = Field(default="SIMULATED", description="Execution status")
    strongest_pro_argument: Optional[str] = Field(default=None, description="The most persuasive PRO argument")
    strongest_con_argument: Optional[str] = Field(default=None, description="The most persuasive CON argument")
    key_rebuttals: List[str] = Field(default_factory=list, description="Key clashes and rebuttals evaluated by the Judge")
    unresolved_questions: List[str] = Field(default_factory=list, description="Unresolved questions and uncertainties")
    confidence: float = Field(default=85.0, ge=0.0, le=100.0, description="Judge confidence in the ruling")
    evaluation_errors: List[str] = Field(default_factory=list, description="Validation or parsing warnings during adjudication")
    performance_metrics: Optional[Dict[str, Any]] = Field(default=None, description="Detailed judge execution latency, token counts, and generation speed")

    @model_validator(mode="before")
    @classmethod
    def normalize_scores_and_aliases(cls, data: Any) -> Any:
        if not isinstance(data, dict):
            return data

        # Normalize criteria scores if provided as simple floats or raw dicts
        for role_key in ("pro_criteria_scores", "con_criteria_scores"):
            raw_c = data.get(role_key)
            if isinstance(raw_c, dict):
                norm_c = {}
                for k, v in raw_c.items():
                    if isinstance(v, (int, float)):
                        norm_c[k] = CriterionScore(score=float(v), max_score=25.0 if "evidence" in k else 20.0 if "logical" in k else 15.0 if k in ("relevance", "rebuttal_effectiveness", "argument_strength") else 10.0, reason="")
                    elif isinstance(v, dict):
                        norm_c[k] = CriterionScore(**v)
                    elif isinstance(v, CriterionScore):
                        norm_c[k] = v
                data[role_key] = norm_c

        # Sync reasoning aliases
        if not data.get("reasoning") and data.get("judge_reasoning"):
            data["reasoning"] = data["judge_reasoning"]
        elif not data.get("judge_reasoning") and data.get("reasoning"):
            data["judge_reasoning"] = data["reasoning"]

        # Sync evidence reliability aliases
        if data.get("evidence_reliability") is not None and "evidence_reliability_score" not in data:
            data["evidence_reliability_score"] = float(data["evidence_reliability"])
        elif data.get("evidence_reliability_score") is not None and "evidence_reliability" not in data:
            data["evidence_reliability"] = float(data["evidence_reliability_score"])

        # Calculate exact totals from criteria scores if available
        pro_c = data.get("pro_criteria_scores")
        if isinstance(pro_c, dict) and len(pro_c) > 0:
            calc_pro = round(sum(item.score if isinstance(item, CriterionScore) else item.get("score", 0.0) for item in pro_c.values()), 1)
            data["pro_total_score"] = calc_pro
            data["pro_score"] = calc_pro
        else:
            base_pro = float(data.get("pro_score", data.get("pro_total_score", 0.0)))
            data["pro_total_score"] = base_pro
            data["pro_score"] = base_pro

        con_c = data.get("con_criteria_scores")
        if isinstance(con_c, dict) and len(con_c) > 0:
            calc_con = round(sum(item.score if isinstance(item, CriterionScore) else item.get("score", 0.0) for item in con_c.values()), 1)
            data["con_total_score"] = calc_con
            data["con_score"] = calc_con
        else:
            base_con = float(data.get("con_score", data.get("con_total_score", 0.0)))
            data["con_total_score"] = base_con
            data["con_score"] = base_con

        # Sync judge_model_used
        if not data.get("judge_model_used") and data.get("judge_model"):
            data["judge_model_used"] = data["judge_model"]
        elif not data.get("judge_model") and data.get("judge_model_used"):
            data["judge_model"] = data["judge_model_used"]

        return data
